"""probe-out/ce_b30_ride.tsv (original engine, seated camera ~10/s) -> Scripts/flight_b30.lua:
samples relative to touchdown, UE cm (x*304.8, -y*304.8, z*304.8), yaw/pitch deltas in degrees."""
import csv, math, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T0, T1 = int(sys.argv[1]), int(sys.argv[2])
rows = [r for r in csv.DictReader(open(os.path.join(ROOT, "probe-out", "ce_b30_ride.tsv")), delimiter="\t")]
st = next(i for i, r in enumerate(rows) if abs(float(r["y"])) > 50)
rows = [r for r in rows[st:] if T0 <= int(r["game_time"]) <= T1]
seen, out = set(), []
for r in rows:
    t = int(r["game_time"])
    if t in seen: continue
    seen.add(t)
    x, y, z, fx, fy, fz = (float(r[k]) for k in ("x", "y", "z", "fx", "fy", "fz"))
    out.append((t, x * 304.8, -y * 304.8, z * 304.8, math.degrees(math.atan2(-fy, fx)), math.degrees(math.asin(max(-1, min(1, fz))))))
# The seated view swings (the rider's head turns), so the Pelican's heading is taken from its
# direction of travel over +-1 s; below 3 m/s it eases to the touchdown heading. Pitch kept level.
L = out[-1]
pts = out
head = []
for i, (t, x, y, z, yw, p) in enumerate(pts):
    a = pts[max(0, i - 5)]; b = pts[min(len(pts) - 1, i + 5)]
    dt = (b[0] - a[0]) / 30 or 1
    vx, vy = (b[1] - a[1]) / dt, (b[2] - a[2]) / dt
    sp = math.hypot(vx, vy)
    head.append((math.degrees(math.atan2(vy, vx)), sp))
land_yaw = None
for (hy, sp) in reversed(head):
    if sp > 300: land_yaw = hy; break
out = []
for (t, x, y, z, yw, p), (hy, sp) in zip(pts, head):
    w = min(1.0, sp / 300.0)
    d = (hy - land_yaw + 180) % 360 - 180
    out.append((t, x, y, z, land_yaw + d * w, 0.0))
L = (L[0], L[1], L[2], L[3], land_yaw, 0.0)
def wrap(a): return (a + 180) % 360 - 180
lines = ["-- GENERATED by devtools/gen_flight.py from the original engine's b30 ride (ticks %d-%d). Do not edit." % (T0, T1),
         "-- { seconds from start, dx, dy, dz (cm from touchdown), dyaw, dpitch (deg from touchdown) }", "return {"]
for t, x, y, z, yw, p in out:
    lines.append("  { %.3f, %.1f, %.1f, %.1f, %.2f, %.2f }," % ((t - T0) / 30, x - L[1], y - L[2], z - L[3], wrap(yw - L[4]), p - L[5]))
lines.append("}")
open(os.path.join(ROOT, "mod", "OriginalCinematics", "Scripts", "flight_b30.lua"), "w").write("\n".join(lines) + "\n")
print(len(out), "samples,", (out[-1][0] - out[0][0]) / 30, "s")
